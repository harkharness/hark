export type Lang = "pt" | "en";
let current: Lang = "pt";

/** Set BEFORE render (overview arrival, HUD boot): t() is then right. */
export function setLang(lang: string | undefined | null) {
  current = lang === "en" ? "en" : "pt";
}
export function lang(): Lang {
  return current;
}

/** Translate a key; {placeholders} filled from vars. */
export function t(key: keyof typeof pt, vars?: Record<string, string | number>): string {
  let out: string = current === "en" ? en[key] : pt[key];
  for (const [k, v] of Object.entries(vars ?? {})) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

